import { test, expect, type Page } from '@playwright/test'
const password = 'Colecionador123!'
const walletAddress = `0x${'a'.repeat(40)}`
async function setup(page: Page, quantity = 1) {
  await page.goto('/cadastro?returnTo=%2Fcarteiras')
  await page.getByRole('textbox', { name: 'Nome de usuário', exact: true }).fill('Nova')
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill('nova@example.com')
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByLabel('Confirmar senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: /^(Criar conta|Criar perfil)$/ }).click()
  await expect(page).toHaveURL('/carteiras')
  const form = page.getByRole('form', { name: 'Dados da carteira principal' })
  await form.getByLabel('Endereço da carteira', { exact: false }).fill(walletAddress)
  await form.getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(form.getByRole('status')).toHaveText('Carteira salva com sucesso.')
  await buy(page, quantity)
  await page.getByRole('link', { name: 'Conectar e finalizar' }).click()
  await expect(page).toHaveURL('/pagamento')
  await expect(page.getByLabel('Nome de exibição', { exact: true })).toHaveValue('Nova')
}
async function buy(page: Page, quantity = 1) {
  await page.goto(`/nfts/emerald-ape-042?quantity=${quantity}`)
  await page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ }).click()
  await expect(page).toHaveURL(/\/carrinho/)
  await expect(page.getByTestId('cart-item')).toHaveCount(1)
}
async function review(page: Page) {
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByText('Carteira conectada · simulação', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Revisar pedido', exact: true }).click()
  await expect(page.getByRole('button', { name: 'Confirmar compra', exact: true })).toBeVisible()
}
async function confirm(page: Page) {
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page).toHaveURL(/\/pedidos\/[a-f0-9-]+/)
}
const total = (page: Page) => page.getByLabel('Total do pedido', { exact: true })

test('checkout confirma por API, conserva recibo e não remove itens adicionados depois', async ({ page }) => {
  await setup(page, 2)
  await review(page)
  await expect(total(page)).toHaveText('2.396 ETH')
  await confirm(page)
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
  const receipt = page.url()
  await expect(total(page)).toHaveText('2.396 ETH')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
  const remaining = await page.evaluate(async () => { const detail = await (await fetch('/api/nfts/emerald-ape-042')).json(); return detail.editions.find((edition: { id: string }) => edition.id === 'limited-50').remaining })
  expect(remaining).toBe(4)
  await page.goto('/carrinho')
  await expect(page.getByRole('heading', { name: 'Seu carrinho está vazio' })).toBeVisible()
  await buy(page)
  await page.evaluate(() => localStorage.setItem('kurio:cart-scenario', 'price-changed'))
  await page.goto(receipt)
  await expect(total(page)).toHaveText('2.396 ETH')
  await page.goto('/carrinho')
  await expect(page.getByTestId('cart-item')).toHaveCount(1)
})

