test('reenvios concorrentes e outra chave da mesma revisão retornam o mesmo pedido', async ({ page }) => {
  await setup(page)
  await review(page)
  await page.evaluate(() => localStorage.setItem('kurio:checkout-scenario', 'pending'))
  await confirm(page)
  const result = await page.evaluate(async () => {
    const database = JSON.parse(localStorage.getItem('kurio:commerce:v1')!)
    const order = database.orders[0]
    const key = crypto.randomUUID()
    const token = sessionStorage.getItem('kurio:session-token')!
    const options = { method: 'POST', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'Idempotency-Key': key }, body: JSON.stringify({ quoteId: order.quoteId }) }
    const responses = await Promise.all([fetch('/api/orders', options), fetch('/api/orders', options)])
    const ids = await Promise.all(responses.map(async response => (await response.json()).id))
    const recovered = await (await fetch(`/api/orders/by-key/${key}`, { headers: { Authorization: `Bearer ${token}` } })).json()
    return { ids, recovered: recovered.id, original: order.id, count: JSON.parse(localStorage.getItem('kurio:commerce:v1')!).orders.length }
  })
  expect(result.count).toBe(1)
  expect(result.ids).toEqual([result.original, result.original])
  expect(result.recovered).toBe(result.original)
})

test('preço alterado exige corrigir carrinho; estoque perdido durante processamento recusa pedido', async ({ page }) => {
  await setup(page)
  await review(page)
  await page.evaluate(() => localStorage.setItem('kurio:cart-scenario', 'price-changed'))
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('O carrinho mudou.')
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('kurio:commerce:v1')!).orders.length)).toBe(0)
  await page.getByRole('link', { name: 'Voltar ao carrinho', exact: true }).click()
  await page.getByRole('button', { name: 'Aceitar novos preços' }).click()
  await expect(page.getByLabel('Total do carrinho', { exact: true })).toHaveText('1.326 ETH')
  await page.getByRole('link', { name: 'Conectar e finalizar' }).click()
  await page.getByRole('button', { name: 'Revisar pedido', exact: true }).click()
  await expect(total(page)).toHaveText('1.326 ETH')
  await page.evaluate(() => localStorage.setItem('kurio:checkout-scenario', 'pending'))
  await confirm(page)
  await page.evaluate(() => { localStorage.setItem('kurio:cart-scenario', 'sold-out'); localStorage.removeItem('kurio:checkout-scenario') })
  await expect(page.getByRole('heading', { name: 'Pagamento recusado', exact: true })).toBeVisible()
  await page.getByRole('link', { name: 'Ver carrinho', exact: true }).click()
  await expect(page.getByTestId('cart-item')).toHaveCount(1)
})

