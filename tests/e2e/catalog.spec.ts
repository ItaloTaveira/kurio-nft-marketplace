import { expect, test, type Page } from '@playwright/test'

const cards = (page: Page) => page.getByTestId('nft-card')
const scenarioKey = 'kurio:catalog-scenario'
async function searchFor(page: Page, query: string) {
  if ((page.viewportSize()?.width ?? 1440) >= 1024) await page.getByRole('button', { name: 'Buscar NFTs', exact: true }).click()
  const input = page.getByRole('searchbox', { name: 'Buscar NFTs' })
  await input.fill(query)
  await input.press('Enter')
}
async function openFilters(page: Page) {
  if ((page.viewportSize()?.width ?? 1440) < 1024) {
    await page.getByRole('button', { name: 'Filtrar NFTs', exact: true }).click()
    return page.getByRole('dialog', { name: 'Filtrar NFTs' })
  }
  return page.getByRole('complementary', { name: 'Filtros do catálogo' })
}

test('paginação, filtros combinados, ordenação, refresh e histórico refletem REST', async ({ page }) => {
  await page.goto('/')
  await expect(cards(page)).toHaveCount(9)
  await page.getByRole('button', { name: 'Página 2', exact: true }).click()
  await expect(page).toHaveURL(/page=2/)
  await expect(cards(page).first()).toContainText('Série 2')
  const filters = await openFilters(page)
  await filters.getByRole('checkbox', { name: 'Arte digital', exact: true }).check()
  await expect(page).not.toHaveURL(/page=2/)
  await filters.getByRole('checkbox', { name: 'Ethereum', exact: true }).check()
  await expect(cards(page)).toHaveCount(2)
  await page.getByRole('combobox', { name: 'Ordenar NFTs' }).selectOption('price-desc')
  if ((page.viewportSize()?.width ?? 1440) < 1024) await filters.getByRole('button', { name: 'Ver resultados' }).click()
  await expect(page).toHaveURL(/sort=price-desc/)
  await page.reload()
  await expect(cards(page)).toHaveCount(2)
  const restoredFilters = await openFilters(page)
  await expect(page.getByRole('combobox', { name: 'Ordenar NFTs' })).toHaveValue('price-desc')
  if ((page.viewportSize()?.width ?? 1440) < 1024) await restoredFilters.getByRole('button', { name: 'Ver resultados' }).click()
  await page.goBack()
  const previousFilters = await openFilters(page)
  await expect(page.getByRole('combobox', { name: 'Ordenar NFTs' })).toHaveValue('recent')
  if ((page.viewportSize()?.width ?? 1440) < 1024) await previousFilters.getByRole('button', { name: 'Ver resultados' }).click()
  await expect(cards(page)).toHaveCount(2)
})

test('busca, vazio e limpeza são operáveis pela interface', async ({ page }) => {
  await page.goto('/')
  await searchFor(page, 'Golden')
  await expect(page).toHaveURL(/q=Golden/)
  await expect(cards(page)).toHaveCount(9)
  for (const card of await cards(page).all()) await expect(card).toContainText('Golden')
  await searchFor(page, 'nao-existe-um-nft-assim')
  await expect(page.getByRole('heading', { name: 'Nenhum NFT encontrado' })).toBeVisible()
  await page.getByRole('button', { name: 'Limpar busca e filtros' }).click()
  await expect(cards(page)).toHaveCount(9)
  await expect(page).not.toHaveURL(/q=/)
})

test('preço é filtrado no servidor e ordem crescente usa valores decimais', async ({ page }) => {
  const request = page.waitForResponse(response => response.url().includes('/api/nfts') && response.url().includes('maxPrice=1.00'))
  await page.goto('/?maxPrice=1.00&sort=price-asc')
  const payload = await (await request).json()
  expect(payload.total).toBe(12)
  expect(payload.items.map((item: { priceEth: string }) => item.priceEth)).toEqual(['0.39', '0.39', '0.39', '0.39', '0.79', '0.79', '0.79', '0.79', '0.99'])
  await expect(cards(page)).toHaveCount(9)
  const filters = await openFilters(page)
  await filters.getByRole('textbox', { name: 'Preço mínimo em ETH' }).fill('2')
  await filters.getByRole('textbox', { name: 'Preço máximo em ETH' }).fill('1')
  await filters.getByRole('button', { name: 'Aplicar', exact: true }).click()
  await expect(filters.getByRole('alert')).toContainText('mínimo menor ou igual')
  await filters.getByRole('textbox', { name: 'Preço mínimo em ETH' }).fill('0,50')
  await filters.getByRole('button', { name: 'Aplicar', exact: true }).click()
  if ((page.viewportSize()?.width ?? 1440) < 1024) await filters.getByRole('button', { name: 'Ver resultados' }).click()
  await expect(cards(page)).toHaveCount(8)
  await expect(page).toHaveURL(/minPrice=0.50/)
})

test('skeleton, falha HTTP e recuperação passam pelos handlers MSW', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, 'slow'), scenarioKey)
  await page.goto('/')
  await expect(page.getByRole('status', { name: 'Carregando NFTs' })).toBeVisible()
  await expect(cards(page)).toHaveCount(9)
  await page.evaluate(key => localStorage.setItem(key, 'error'), scenarioKey)
  await page.getByRole('button', { name: 'Em alta', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Não foi possível carregar')
  await page.evaluate(key => localStorage.setItem(key, 'success'), scenarioKey)
  await page.getByRole('button', { name: 'Tentar novamente' }).click()
  await expect(cards(page)).toHaveCount(9)
  await expect(page.getByRole('alert')).toHaveCount(0)
})

test('resposta antiga não substitui a busca mais recente', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, 'out-of-order'), scenarioKey)
  await page.goto('/')
  await searchFor(page, 'Ape')
  await searchFor(page, 'Golden')
  await expect(cards(page)).toHaveCount(9)
  await expect(cards(page).first()).toContainText('Golden')
  // Espera o prazo determinístico do handler antigo, sem bloquear os demais testes.
  await expect.poll(async () => page.evaluate(() => performance.now())).toBeGreaterThan(2200)
  await expect(cards(page).first()).toContainText('Golden')
  await expect(page).toHaveURL(/q=Golden/)
})

test('recortes de lançamentos e em alta mudam a API e reiniciam a página', async ({ page }) => {
  await page.goto('/?page=2')
  await expect(cards(page)).toHaveCount(9)
  const newest = page.waitForResponse(response => response.url().includes('/api/nfts') && response.url().includes('tab=new'))
  await page.getByRole('button', { name: 'Novos lançamentos', exact: true }).click()
  expect((await (await newest).json()).total).toBe(18)
  await expect(page).not.toHaveURL(/page=2/)
  await expect(page.getByRole('button', { name: 'Novos lançamentos', exact: true })).toHaveAttribute('aria-pressed', 'true')
})

test('URL preserva as 18 casas decimais do preço até a requisição REST', async ({ page }) => {
  const response = page.waitForResponse(value => value.url().includes('/api/nfts') && new URL(value.url()).searchParams.get('minPrice') === '0.999999999999999999')
  await page.goto('/?minPrice=0.999999999999999999&maxPrice=1.19')
  const payload = await (await response).json()
  expect(payload.total).toBe(4)
  expect(payload.items.every((item: { priceEth: string }) => item.priceEth === '1.19')).toBe(true)
  await expect(cards(page)).toHaveCount(4)
  await page.reload()
  await expect(cards(page)).toHaveCount(4)
})

test('painel mobile contém o foco e devolve ao botão ao fechar', async ({ page }) => {
  test.skip((page.viewportSize()?.width ?? 1440) >= 1024, 'O desktop usa a barra lateral')
  await page.goto('/')
  const trigger = page.getByRole('button', { name: 'Filtrar NFTs', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Filtrar NFTs' })
  await expect(dialog).toBeVisible()
  await page.keyboard.press('Shift+Tab')
  await expect(dialog.getByRole('button', { name: 'Ver resultados' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Fechar painel' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})
