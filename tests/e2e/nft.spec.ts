import { expect, test } from '@playwright/test'

const path = '/nfts/emerald-ape-042'
const scenarioKey = 'kurio:nft-scenario'

test('card abre o NFT e o retorno preserva a busca e a página do catálogo', async ({ page }) => {
  await page.goto('/?q=Golden&page=2&sort=price-asc')
  const card = page.getByTestId('nft-card').first()
  await expect(card).toBeVisible()
  const name = await card.getByRole('heading').innerText()
  await card.getByRole('link', { name: `Ver detalhes de ${name}`, exact: true }).click()
  await expect(page).toHaveURL(/\/nfts\//)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText(name)
  const returnLink = page.viewportSize()!.width >= 1024 ? page.getByRole('navigation', { name: 'Caminho de navegação' }).getByRole('link', { name: 'Mercado', exact: true }) : page.getByRole('link', { name: 'Voltar ao catálogo', exact: true })
  await returnLink.click()
  await expect(page).toHaveURL(/q=Golden/)
  await expect(page).toHaveURL(/page=2/)
  await expect(page).toHaveURL(/sort=price-asc/)
  await expect(page.getByTestId('nft-card').first().getByRole('heading')).toHaveText(name)
})

test('acesso direto e refresh preservam edição, quantidade e subtotal decimal', async ({ page }) => {
  const response = page.waitForResponse(value => new URL(value.url()).pathname === '/api/nfts/emerald-ape-042')
  await page.goto(`${path}?edition=limited-50&quantity=3`)
  const data = await (await response).json()
  expect(data.editions.find((edition: { id: string }) => edition.id === 'limited-50').maxPerOrder).toBe(3)
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Emerald Ape #042')
  await expect(page.getByRole('spinbutton', { name: 'Quantidade', exact: true })).toHaveValue('3')
  await expect(page.getByLabel('Subtotal da seleção', { exact: true })).toHaveText('3.57 ETH')
  await expect(page.getByRole('button', { name: 'Aumentar quantidade' })).toBeDisabled()
  await page.reload()
  await expect(page.getByRole('spinbutton', { name: 'Quantidade', exact: true })).toHaveValue('3')
  await expect(page.getByRole('radio', { name: 'Edição 1/50', exact: true })).toBeChecked()
  await page.getByRole('radio', { name: 'Edição 1/10', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Quantidade', exact: true })).toHaveValue('1')
  await expect(page.getByLabel('Subtotal da seleção', { exact: true })).toHaveText('1.79 ETH')
  await expect(page).toHaveURL(/edition=limited-10/)
})

test('quantidade rejeita frações e excesso; edição esgotada não pode ser escolhida', async ({ page }) => {
  await page.goto(path)
  const quantity = page.getByRole('spinbutton', { name: 'Quantidade', exact: true })
  await expect(quantity).toHaveValue('1')
  await expect(page.getByRole('radio', { name: 'Edição 1/1 — esgotada', exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Diminuir quantidade' })).toBeDisabled()
  await quantity.fill('99')
  await quantity.press('Tab')
  await expect(page.getByRole('alert')).toHaveText('Escolha de 1 a 3 unidades.')
  await expect(quantity).toHaveValue('1')
  await quantity.fill('1.5')
  await quantity.press('Enter')
  await expect(quantity).toHaveValue('1')
  await page.getByRole('button', { name: 'Aumentar quantidade' }).click()
  await expect(quantity).toHaveValue('2')
  await expect(page.getByLabel('Subtotal da seleção', { exact: true })).toHaveText('2.38 ETH')
})

test('estoque reduzido limita a seleção recuperada da URL', async ({ page }) => {
  await page.addInitScript(key => localStorage.setItem(key, 'stock-reduced'), scenarioKey)
  await page.goto(`${path}?quantity=3`)
  const quantity = page.getByRole('spinbutton', { name: 'Quantidade', exact: true })
  await expect(quantity).toHaveValue('1')
  await expect(page.getByRole('button', { name: 'Aumentar quantidade' })).toBeDisabled()
  await expect(page).not.toHaveURL(/quantity=3/)
})

test('NFT inexistente, edição desconhecida e esgotamento têm estados próprios', async ({ page }) => {
  await page.goto('/nfts/nao-existe')
  await expect(page.getByRole('heading', { name: 'NFT não encontrado', exact: true })).toBeVisible()
  await page.goto(`${path}?edition=desconhecida`)
  await expect(page.getByRole('alert')).toContainText('A edição selecionada não existe')
  await expect(page.getByRole('spinbutton', { name: 'Quantidade', exact: true })).toBeDisabled()
  await page.getByRole('radio', { name: 'Edição 1/50', exact: true }).click()
  await expect(page.getByRole('spinbutton', { name: 'Quantidade', exact: true })).toBeEnabled()
  await page.evaluate(key => localStorage.setItem(key, 'sold-out'), scenarioKey)
  await page.reload()
  await expect(page.getByText('Este NFT está esgotado.', { exact: true })).toBeVisible()
  await expect(page.getByRole('spinbutton', { name: 'Quantidade', exact: true })).toBeDisabled()
})

test('galeria amplia, troca miniatura por teclado e devolve o foco', async ({ page }) => {
  await page.goto(path)
  const trigger = page.getByRole('button', { name: 'Ampliar imagem de Emerald Ape #042', exact: true })
  await trigger.click()
  const dialog = page.getByRole('dialog', { name: 'Emerald Ape #042', exact: true })
  await expect(dialog).toBeVisible()
  const radio = dialog.getByRole('radio', { name: 'Imagem 3', exact: true })
  await radio.click()
  await expect(radio).toBeChecked()
  await radio.press('ArrowRight')
  await expect(dialog.getByRole('radio', { name: 'Imagem 4', exact: true })).toBeChecked()
  await expect(dialog.getByRole('img', { name: /imagem 4$/ })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(trigger).toBeFocused()
})

test('detalhes e avaliações têm navegação por teclado e expansão de avaliações', async ({ page }) => {
  await page.goto(path)
  const details = page.getByRole('tab', { name: 'Detalhes do NFT', exact: true })
  await details.scrollIntoViewIfNeeded()
  await details.focus()
  await page.keyboard.press('ArrowRight')
  const reviews = page.getByRole('tab', { name: 'Avaliações de colecionadores (19)', exact: true })
  await expect(reviews).toBeFocused()
  await expect(reviews).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByText('Exibindo 3 de 19 avaliações.', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Mostrar mais avaliações', exact: true }).click()
  await expect(page.getByText('Exibindo 8 de 19 avaliações.', { exact: true })).toBeVisible()
})

test('skeleton, falha de rede e recuperação do detalhe usam MSW', async ({ page }) => {
  await page.addInitScript(key => { if (localStorage.getItem(key) === null) localStorage.setItem(key, 'slow') }, scenarioKey)
  await page.goto(path)
  await expect(page.getByRole('status', { name: 'Carregando detalhes do NFT', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Emerald Ape #042')
  await page.evaluate(key => localStorage.setItem(key, 'offline'), scenarioKey)
  // Muda para outro recurso, sem aproveitar o cache da consulta anterior.
  await page.goto('/nfts/sage-nomad-009')
  await expect(page.getByRole('heading', { name: 'Não foi possível carregar este NFT', exact: true })).toBeVisible()
  await page.evaluate(key => localStorage.setItem(key, 'success'), scenarioKey)
  await page.getByRole('button', { name: 'Tentar novamente', exact: true }).click()
  await expect(page.getByRole('heading', { level: 1 })).toHaveText('Sage Nomad #009')
})
