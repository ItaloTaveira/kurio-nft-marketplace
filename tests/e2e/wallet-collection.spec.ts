import { test, expect, type Page } from '@playwright/test'
async function login(page: Page, email = 'nova@kurio.test') {
  await page.goto('/entrar?returnTo=%2Fcarteiras')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('Kurio123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('/carteiras')
}
async function prepare(page: Page, network: 'ethereum' | 'polygon', nft: string, quantity = 1) {
  await login(page)
  const form = page.getByRole('form', { name: 'Dados da carteira principal' })
  await form.getByLabel('Rede', { exact: false }).selectOption(network)
  await form.getByRole('button', { name: 'Gerar endereço fictício', exact: true }).click()
  await expect(form.getByLabel('Endereço da carteira', { exact: false })).toHaveValue(/^0x[0-9a-f]{40}$/)
  await form.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(form.getByRole('status')).toHaveText('Carteira salva com sucesso.')
  await page.goto(`/nfts/${nft}?quantity=${quantity}`)
  await page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ }).click()
  await page.getByRole('link', { name: 'Conectar e finalizar', exact: true }).click()
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await page.getByRole('button', { name: 'Revisar pedido', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Revisar pedido', exact: true })).toBeVisible()
}
const collection = (page: Page) => page.getByRole('region', { name: 'Meus NFTs na carteira', exact: true })

test('compra Polygon entrega unidades na carteira, persiste e isola por conta', async ({ page }) => {
  await prepare(page, 'polygon', 'sage-nomad-009', 2)
  await expect(page.getByLabel('Taxa do pedido', { exact: true })).toHaveText('0.003 ETH')
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
  const receipt = page.url()
  await page.getByRole('link', { name: 'Ver NFTs na carteira', exact: true }).click()
  await expect(collection(page).getByTestId('wallet-nft')).toHaveCount(1)
  await expect(collection(page)).toContainText('Sage Nomad #009')
  await expect(collection(page)).toContainText('Polygon')
  await expect(collection(page)).toContainText('Quantidade: 2')
  await page.goto(receipt)
  await page.reload()
  await page.getByRole('link', { name: 'Ver NFTs na carteira', exact: true }).click()
  await expect(collection(page).getByTestId('wallet-nft')).toHaveCount(1)
  await expect(collection(page)).toContainText('Quantidade: 2')
  await page.getByLabel('Conta de Nova', { exact: true }).filter({ visible: true }).click()
  await page.locator('.account-menu-panel:visible').getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL('/')
  await login(page, 'leo@kurio.test')
  await expect(collection(page)).toContainText('Você ainda não possui NFTs de compras confirmadas.')
  await expect(collection(page).getByTestId('wallet-nft')).toHaveCount(0)
})

test('pedidos pendentes e recusados não entregam NFTs', async ({ page }) => {
  await prepare(page, 'ethereum', 'emerald-ape-042')
  await page.evaluate(() => localStorage.setItem('kurio:checkout-scenario', 'pending'))
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pedido em processamento', exact: true })).toBeVisible()
  const receipt = page.url()
  await page.goto('/carteiras')
  await expect(collection(page)).toContainText('Você ainda não possui NFTs de compras confirmadas.')
  await page.evaluate(() => { localStorage.setItem('kurio:cart-scenario', 'sold-out'); localStorage.removeItem('kurio:checkout-scenario') })
  await page.goto(receipt)
  await expect(page.getByRole('heading', { name: 'Pagamento recusado', exact: true })).toBeVisible()
  await page.goto('/carteiras')
  await expect(collection(page)).toContainText('Você ainda não possui NFTs de compras confirmadas.')
})
