import { test, expect, type Page } from '@playwright/test'
async function login(page: Page) {
  await page.goto('/entrar?returnTo=%2Fcarteiras')
  await page.getByLabel('E-mail', { exact: true }).fill('nova@kurio.test')
  await page.getByLabel('Senha', { exact: true }).fill('Kurio123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('/carteiras')
}
const primary = (page: Page) => page.getByRole('form', { name: 'Dados da carteira principal' })
test('gera endereços fictícios para cada rede e mantém a carteira após refresh', async ({ page }) => {
  await login(page)
  const form = primary(page)
  for (const network of ['ethereum', 'polygon', 'solana']) {
    await form.getByLabel('Rede', { exact: false }).selectOption(network)
    await form.getByRole('button', { name: 'Gerar endereço fictício', exact: true }).click()
    await expect(form.getByLabel('Endereço da carteira', { exact: false })).toHaveValue(network === 'solana' ? /^[1-9A-HJ-NP-Za-km-z]{32,44}$/ : /^0x[0-9a-f]{40}$/)
    await form.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
    await expect(form.getByRole('status')).toHaveText('Carteira salva com sucesso.')
  }
  const address = await form.getByLabel('Endereço da carteira', { exact: false }).inputValue()
  await page.reload()
  await expect(form.getByLabel('Rede', { exact: false })).toHaveValue('solana')
  await expect(form.getByLabel('Endereço da carteira', { exact: false })).toHaveValue(address)
})
test('falha ao gerar permite repetir e comprar com a carteira fictícia', async ({ page }) => {
  await login(page)
  const form = primary(page)
  await expect(form.getByRole('button', { name: 'Gerar endereço fictício', exact: true })).toBeVisible()
  await page.evaluate(() => localStorage.setItem('kurio:account-scenario', 'mutation-error'))
  await form.getByRole('button', { name: 'Gerar endereço fictício', exact: true }).click()
  await expect(form.getByRole('alert')).toContainText('indisponível')
  await expect(form.getByLabel('Endereço da carteira', { exact: false })).toHaveValue('')
  await page.evaluate(() => localStorage.removeItem('kurio:account-scenario'))
  await form.getByRole('button', { name: 'Gerar endereço fictício', exact: true }).click()
  await expect(form.getByLabel('Endereço da carteira', { exact: false })).toHaveValue(/^0x[0-9a-f]{40}$/)
  await form.getByRole('button', { name: 'Salvar carteira', exact: true }).click()
  await expect(form.getByRole('status')).toHaveText('Carteira salva com sucesso.')
  await page.goto('/nfts/emerald-ape-042')
  await page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ }).click()
  await page.getByRole('link', { name: 'Conectar e finalizar', exact: true }).click()
  const review = page.getByRole('button', { name: 'Revisar pedido', exact: true })
  await expect(review).toBeVisible()
  await expect(review).toBeDisabled()
  await expect(page.getByRole('button', { name: 'Confirmar compra', exact: true })).toHaveCount(0)
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByText('Carteira conectada · simulação', { exact: true })).toBeVisible()
  await expect(review).toBeEnabled()
  await review.click()
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
})
