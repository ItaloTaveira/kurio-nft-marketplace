import { test, expect, type Page } from '@playwright/test'
const password = 'Colecionador123!'
const newPassword = 'NovaSenha456!'
const addressA = `0x${'a'.repeat(40)}`
const addressB = `0x${'b'.repeat(40)}`
async function createAccount(page: Page, email = 'nova@example.com', name = 'Nova', destination = '/perfil') {
  await page.goto(`/cadastro?returnTo=${encodeURIComponent(destination)}`)
  await page.getByRole('textbox', { name: 'Nome de usuário', exact: true }).fill(name)
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(password)
  await page.getByLabel('Confirmar senha', { exact: true }).fill(password)
  await page.getByRole('button', { name: /^(Criar conta|Criar perfil)$/ }).click()
  await expect(page).toHaveURL(destination)
  await expect(page.getByRole('heading', { level: 1 })).toBeVisible()
}
async function signOut(page: Page, name = 'Nova') {
  await page.getByLabel(`Conta de ${name}`, { exact: true }).filter({ visible: true }).click()
  await page.locator('.account-menu-panel:visible').getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/entrar/)
}
async function signIn(page: Page, secret = password, email = 'nova@example.com') {
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill(secret)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
}
const primary = (page: Page) => page.getByRole('form', { name: 'Dados da carteira principal' })
const secondary = (page: Page) => page.getByRole('form', { name: 'Dados da carteira secundária' })

test('rotas privadas redirecionam e retomam o destino após cadastro', async ({ page }) => {
  await page.goto('/carteiras')
  await expect(page).toHaveURL(/\/entrar\?returnTo=%2Fcarteiras/)
  await expect(page.getByRole('heading', { name: 'Carteira principal' })).toHaveCount(0)
  await createAccount(page, 'nova@example.com', 'Nova', '/carteiras')
  await expect(primary(page)).toBeVisible()
  await expect(primary(page).getByLabel('E-mail', { exact: false })).toHaveValue('nova@example.com')
})

test('perfil e avatar persistem; remoção de avatar também é confirmada pela API', async ({ page }) => {
  await createAccount(page)
  await page.getByLabel('Nome de exibição', { exact: false }).fill('Nova Arte')
  await page.getByLabel('Nome de usuário', { exact: false }).fill('nova.arte')
  await page.getByLabel('Nome ENS', { exact: false }).fill('nova')
  await page.getByLabel('Apelido da carteira', { exact: false }).fill('Minha coleção')
  const image = await page.evaluate(() => { const canvas = document.createElement('canvas'); canvas.width = 8; canvas.height = 8; canvas.getContext('2d')!.fillRect(0, 0, 8, 8); return canvas.toDataURL('image/png').split(',')[1] })
  await page.getByLabel('Alterar avatar').setInputFiles({ name: 'avatar.png', mimeType: 'image/png', buffer: Buffer.from(image, 'base64') })
  await expect(page.getByRole('img', { name: 'Prévia do avatar' })).toBeVisible()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Perfil atualizado com sucesso.' })).toBeVisible()
  await page.reload()
  await expect(page.getByLabel('Nome de exibição', { exact: false })).toHaveValue('Nova Arte')
  await expect(page.getByLabel('Nome de usuário', { exact: false })).toHaveValue('nova.arte')
  await expect(page.getByRole('img', { name: 'Prévia do avatar' })).toBeVisible()
  await page.getByRole('button', { name: 'Remover', exact: true }).click()
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Perfil atualizado com sucesso.' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('img', { name: 'Sem avatar' })).toBeVisible()
})

test('senha incorreta não salva perfil parcialmente; nova senha substitui a anterior', async ({ page }) => {
  await createAccount(page)
  await page.getByLabel('Nome de exibição', { exact: false }).fill('Nome novo')
  await page.getByLabel('Senha atual', { exact: true }).fill('SenhaErrada')
  await page.getByLabel('Nova senha', { exact: true }).fill(newPassword)
  await page.getByLabel('Confirmar nova senha', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('A senha atual está incorreta.')
  await page.reload()
  await expect(page.getByLabel('Nome de exibição', { exact: false })).toHaveValue('Nova')
  await page.getByLabel('Senha atual', { exact: true }).fill(password)
  await page.getByLabel('Nova senha', { exact: true }).fill(newPassword)
  await page.getByLabel('Confirmar nova senha', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Perfil e senha atualizados.' })).toBeVisible()
  await expect(page.getByLabel('Senha atual', { exact: true })).toHaveValue('')
  await signOut(page)
  await signIn(page)
  await expect(page.getByRole('alert')).toHaveText('E-mail ou senha incorretos.')
  await page.getByLabel('Senha', { exact: true }).fill(newPassword)
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('/perfil')
})

test('carteiras validam rede/endereço, persistem e podem compartilhar a principal', async ({ page }) => {
  await createAccount(page, 'nova@example.com', 'Nova', '/carteiras')
  await primary(page).getByLabel('Endereço da carteira', { exact: false }).fill('invalido')
  await primary(page).getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(primary(page).getByRole('alert')).toContainText('0x seguido de 40')
  await primary(page).getByLabel('Endereço da carteira', { exact: false }).fill(addressA)
  await primary(page).getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(primary(page).getByRole('status')).toHaveText('Carteira salva com sucesso.')
  await page.getByRole('checkbox', { name: 'Igual à carteira principal' }).click()
  await expect(page.getByRole('checkbox', { name: 'Igual à carteira principal' })).toBeChecked()
  await expect(page.getByText('A carteira secundária acompanha a principal:', { exact: false })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('checkbox', { name: 'Igual à carteira principal' })).toBeChecked()
  await page.getByRole('checkbox', { name: 'Igual à carteira principal' }).click()
  await expect(page.getByRole('checkbox', { name: 'Igual à carteira principal' })).not.toBeChecked()
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click()
  await secondary(page).getByLabel('Endereço da carteira', { exact: false }).fill(addressA)
  await secondary(page).getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(secondary(page).getByRole('alert')).toContainText('Este endereço já está na outra carteira')
  await secondary(page).getByLabel('Endereço da carteira', { exact: false }).fill(addressB)
  await secondary(page).getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(secondary(page).getByRole('status')).toHaveText('Carteira salva com sucesso.')
  await page.reload()
  await expect(primary(page).getByLabel('Endereço da carteira', { exact: false })).toHaveValue(addressA)
  await expect(secondary(page).getByLabel('Endereço da carteira', { exact: false })).toHaveValue(addressB)
  await secondary(page).getByLabel('Rede', { exact: false }).selectOption('solana')
  await secondary(page).getByLabel('Endereço da carteira', { exact: false }).fill('11111111111111111111111111111111')
  await secondary(page).getByRole('button', { name: 'Salvar carteira' }).click()
  await expect(secondary(page).getByRole('status')).toHaveText('Carteira salva com sucesso.')
})

test('falha de gravação mantém formulário; expiração exige login e preserva dados salvos', async ({ page }) => {
  await createAccount(page)
  await page.getByLabel('Nome de exibição', { exact: false }).fill('Nova alterada')
  await page.evaluate(() => localStorage.setItem('kurio:account-scenario', 'mutation-error'))
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('O serviço de perfil e carteiras está indisponível.')
  await expect(page.getByLabel('Nome de exibição', { exact: false })).toHaveValue('Nova alterada')
  await page.evaluate(() => localStorage.removeItem('kurio:account-scenario'))
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Perfil atualizado com sucesso.' })).toBeVisible()
  await page.evaluate(() => localStorage.setItem('kurio:auth-scenario', 'expired'))
  await page.getByRole('button', { name: 'Salvar', exact: true }).click()
  await expect(page).toHaveURL(/\/entrar\?returnTo=%2Fperfil/)
  await page.evaluate(() => localStorage.removeItem('kurio:auth-scenario'))
  await signIn(page)
  await expect(page).toHaveURL('/perfil')
  await expect(page.getByLabel('Nome de exibição', { exact: false })).toHaveValue('Nova alterada')
})

