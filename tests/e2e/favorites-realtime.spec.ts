import { expect, test, type Page } from '@playwright/test'
async function login(page: Page, email = 'nova@kurio.test') {
  await page.goto('/entrar?returnTo=%2F')
  await page.getByLabel('E-mail', { exact: true }).fill(email)
  await page.getByLabel('Senha', { exact: true }).fill('Kurio123!')
  await page.getByRole('button', { name: 'Entrar', exact: true }).click()
  await expect(page).toHaveURL('/')
}
async function event(page: Page, payload: Record<string, unknown>) { return page.evaluate(async payload => (await fetch('/api/mock/events', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(payload) })).status, payload) }
async function buy(page: Page) {
  await page.goto('/nfts/emerald-ape-042')
  await page.getByRole('button', { name: /^(COMPRAR|Comprar NFT)$/ }).click()
  await expect(page).toHaveURL(/\/carrinho/)
  await expect(page.getByLabel('Total do carrinho', { exact: true })).toHaveText('1.206 ETH')
}
test('favoritos persistem, fazem rollback e são isolados por usuário', async ({ page }) => {
  await login(page)
  const add = page.getByRole('button', { name: 'Adicionar Emerald Ape #042 aos favoritos', exact: true })
  await add.click()
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true })).toBeEnabled()
  await page.goto('/favoritos')
  await expect(page.getByTestId('nft-card')).toHaveCount(1)
  await page.reload()
  await expect(page.getByTestId('nft-card')).toHaveCount(1)
  await page.evaluate(() => localStorage.setItem('kurio:favorites-scenario', 'mutation-error'))
  await page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true }).click()
  await expect(page.getByTestId('nft-card')).toHaveCount(1)
  await expect(page.getByRole('alert')).toContainText('Não foi possível atualizar seus favoritos')
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true })).toBeEnabled()
  await page.evaluate(() => localStorage.removeItem('kurio:favorites-scenario'))
  const removed = page.waitForResponse(response => response.url().includes('/api/favorites/') && response.request().method() === 'DELETE' && response.status() === 200)
  await page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true }).click()
  await removed
  await expect(page.getByTestId('nft-card')).toHaveCount(0)
  await page.goto('/nfts/emerald-ape-042')
  await page.getByRole('button', { name: 'Adicionar Emerald Ape #042 aos favoritos', exact: true }).filter({ visible: true }).click()
  await expect(page.getByRole('button', { name: 'Remover Emerald Ape #042 dos favoritos', exact: true }).filter({ visible: true })).toBeEnabled()
  await page.goto('/favoritos')
  await page.getByLabel('Conta de Nova', { exact: true }).filter({ visible: true }).click()
  await page.locator('.account-menu-panel:visible').getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/entrar/)
  await login(page, 'leo@kurio.test')
  await page.goto('/favoritos')
  await expect(page.getByTestId('nft-card')).toHaveCount(0)
})
test('Socket.IO atualiza carrinho, ignora duplicata/antigo e reconcilia após interrupção', async ({ page }) => {
  await buy(page)
  await expect(page.getByTestId('realtime-state')).toHaveText('Conectado')
  expect(await event(page, { type: 'nft', nftId: 'emerald-ape-042', priceEth: '1.50' })).toBe(200)
  await expect(page.getByLabel('Total do carrinho', { exact: true })).toHaveText('1.516 ETH')
  await expect(page.getByRole('alert')).toContainText('preço alterado')
  await event(page, { type: 'nft', nftId: 'emerald-ape-042', mode: 'duplicate' })
  await event(page, { type: 'nft', nftId: 'emerald-ape-042', priceEth: '0.01', mode: 'old' })
  await expect(page.getByLabel('Total do carrinho', { exact: true })).toHaveText('1.516 ETH')
  await event(page, { type: 'disconnect', durationMs: 1800 })
  await expect(page.getByText('Conexão ao vivo interrompida. Reconectando…')).toBeVisible()
  await event(page, { type: 'nft', nftId: 'emerald-ape-042', remaining: 0 })
  await expect(page.getByText('Conexão restabelecida. Dados atualizados pela API.')).toBeVisible({ timeout: 10000 })
  await expect(page.getByRole('alert')).toContainText('edição esgotada')
  await expect(page.getByTestId('realtime-state')).toHaveText('Conectado')
})

test('order.updated confirma por REST e o recibo não recebe eventos de outra conta', async ({ page }) => {
  await login(page)
  await page.evaluate(async () => {
    const token = sessionStorage.getItem('kurio:session-token')!
    await fetch('/api/wallets/primary', { method: 'PUT', headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', 'If-Match': '"0"' }, body: JSON.stringify({ name: 'Nova', alias: 'Principal', profileName: 'Nova', email: 'nova@kurio.test', network: 'ethereum', provider: 'WalletConnect', address: `0x${'a'.repeat(40)}`, secondaryAddress: '', referralCode: '', ens: '' }) })
  })
  await buy(page)
  await page.getByRole('link', { name: 'Conectar e finalizar' }).click()
  await page.getByRole('button', { name: 'Conectar carteira', exact: true }).click()
  await expect(page.getByText('Carteira conectada · simulação', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Revisar pedido', exact: true }).click()
  await page.evaluate(() => localStorage.setItem('kurio:checkout-scenario', 'pending'))
  await page.getByRole('button', { name: 'Confirmar compra', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Pedido em processamento', exact: true })).toBeVisible()
  await expect(page.getByTestId('realtime-state')).toHaveText('Conectado')
  await page.evaluate(() => localStorage.removeItem('kurio:checkout-scenario'))
  await expect(page.getByText('Status do pedido atualizado. Consultando confirmação na API.')).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Compra confirmada', exact: true })).toBeVisible()
  const receipt = page.url()
  await page.getByLabel('Conta de Nova', { exact: true }).filter({ visible: true }).click()
  await page.locator('.account-menu-panel:visible').getByRole('button', { name: 'Sair', exact: true }).click()
  await expect(page).toHaveURL(/\/entrar/)
  await login(page, 'leo@kurio.test')
  await page.goto(receipt)
  await expect(page.getByRole('heading', { name: 'Pedido não encontrado nesta conta' })).toBeVisible()
  await expect(page.getByTestId('order-item')).toHaveCount(0)
})
